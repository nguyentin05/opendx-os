ROOT = Path(__file__).resolve().parents[2]


def api(live, path, body=None, method=None, content_type='application/json', authorization=True):
    credential = base64.b64encode((live.config.get('KESTRA_USER', 'admin@dxos.local') + ':' + live.config['KESTRA_PASSWORD']).encode()).decode()
    headers = {'Content-Type': content_type}
    if authorization:
        headers['Authorization'] = 'Basic ' + credential
    req = Request('http://localhost:' + live.config.get('KESTRA_PORT', '18082') + path, body, headers, method=method)
    try:
        with urlopen(req, timeout=25) as response:
            raw = response.read()
            return json.loads(raw) if raw else None
    except HTTPError as error:
        # Do not print URLs or body: they can include webhook keys and tokens.
        private_json(ROOT / 'build/integration/kestra-last-error.json', {'status': error.code, 'response': error.read().decode(errors='replace')})
        raise Refused('Kestra operation rejected: HTTP ' + str(error.code) + ' (private diagnostic saved)') from None


def declarations(live):
    rows = json.loads(live.sql("SELECT coalesce(json_agg(json_build_object('workspace_id',workspace_id,'app_id',app_id,'version',version,'manifest_spec',manifest_spec)), '[]') FROM core.app_registry WHERE status='Ready'"))
    packages = {}
    for path in (ROOT / 'apps').glob('*/manifest.yaml'):
        manifest = yaml.safe_load(path.read_text())
        packages[manifest['metadata']['name']] = (path.parent, manifest)
    entries = []
    for row in rows:
        package, manifest = packages[row['app_id']]
        if manifest['metadata']['version'] != row['version'] or manifest['spec'] != row['manifest_spec']:
            raise Refused('Ready snapshot differs from package; republish before workflow deployment')
        subscribed = [w for w in manifest['spec']['workflows'] if 'command.committed' in w['subscribedEvents']]
        if len(subscribed) != 1:
            raise Refused('single-destination publisher requires exactly one subscribed workflow')
        binding = subscribed[0]
        flow = yaml.safe_load((package / binding['file']).read_text())
        if flow['id'] != binding['id']:
            raise Refused('workflow identity differs from manifest')
        webhooks = [t for t in flow['triggers'] if t['type'] == 'io.kestra.plugin.core.trigger.Webhook']
        if len(webhooks) != 1 or webhooks[0]['key'] != "{{ secret('DXOS_WEBHOOK_KEY') }}":
            raise Refused('unsupported declared webhook configuration')
        entries.append((row, flow))
    if not entries:
        raise Refused('no Ready workflows to deploy')
    return entries


def update_env(live, updates):
    live.config.update(updates)
    path = ROOT / '.env.integration'
    if path.is_symlink():
        raise Refused('private environment cannot be symlink')
    fd = os.open(path, os.O_WRONLY | os.O_TRUNC)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, 'w') as stream:
        stream.write(''.join(k + '=' + v + '\n' for k, v in live.config.items()))


def provision_database(live):
    if 'KESTRA_DATABASE_PASSWORD' not in live.config:
        update_env(live, {'KESTRA_DATABASE_PASSWORD': secrets.token_urlsafe(36)})
    password = live.config['KESTRA_DATABASE_PASSWORD']
    if not all(c.isalnum() or c in '-_' for c in password):
        raise Refused('Kestra bootstrap password must be generated by this helper')
    exists = live.sql("SELECT count(*) FROM pg_roles WHERE rolname='dxos_kestra'", 'bootstrap')
    if exists == '0':
        live.sql("CREATE ROLE dxos_kestra LOGIN PASSWORD '%s' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS" % password, 'bootstrap')
    if live.sql("SELECT count(*) FROM pg_database WHERE datname='dxos_kestra'", 'bootstrap') == '0':
        live.sql('CREATE DATABASE dxos_kestra OWNER dxos_kestra', 'bootstrap')
        live.sql('REVOKE CONNECT ON DATABASE dxos_kestra FROM PUBLIC', 'bootstrap')
    if live.sql("SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolbypassrls FROM pg_roles WHERE rolname='dxos_kestra'", 'bootstrap') != 'f':
        raise Refused('Kestra runtime role exceeds its database owner scope')


def deploy(live, reload=False):
    entries = [(r, f) for r, f in declarations(live) if r['workspace_id'] == live.fixture['actors']['workflow']['workspace_id']]
    provision_database(live)
    keypath = ROOT / 'build/integration/webhook-key.json'
    key = json.loads(keypath.read_text()) if keypath.exists() else secrets.token_urlsafe(36)
    private_json(keypath, key)
    routes = [{'workspace_id': r['workspace_id'], 'app_id': r['app_id'], 'version': r['version'], 'workflow_id': f['id'], 'endpoint': 'http://kestra:8080/api/v1/executions/webhook/' + f['namespace'] + '/' + f['id'] + '/' + key} for r, f in entries]
    private_json(ROOT / 'build/integration/workflow-routes.json', routes)
    token = live.tokens['TEST_WORKFLOW_TOKEN']
    claims = json.loads(base64.urlsafe_b64decode(token.split('.')[1] + '=='))
    actor = live.fixture['actors']['workflow']
    hasura = claims.get('https://hasura.io/jwt/claims', {})
    if claims['sub'] != actor['sub'] or hasura.get('x-hasura-workspace-id') != actor['workspace_id'] or actor['roles'][0] not in hasura.get('x-hasura-allowed-roles', []) or time.time() + 90 >= claims['exp']:
        raise Refused('renewed workflow token identity/lifetime invalid')
    # Real Keycloak token is verified cryptographically by the effect endpoint;
    # these checks prevent delivering a mismatched private configuration.
    values = {'DXOS_WEBHOOK_KEY': key, 'DXOS_PROCESS_URL': 'http://cap-process:8081', 'DXOS_WORKFLOW_TOKEN': token}
    path = ROOT / 'build/integration/kestra.env'
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, 'w') as stream:
        stream.write(''.join('SECRET_' + k + '=' + base64.b64encode(v.encode()).decode() + '\n' for k, v in values.items()))
    credential = base64.b64encode((live.config.get('KESTRA_USER', 'admin@dxos.local') + ':' + live.config['KESTRA_PASSWORD']).encode()).decode()
    update_env(live, {'INTEGRATION_UID': str(os.getuid()), 'INTEGRATION_GID': str(os.getgid()), 'KESTRA_AUTH_SCHEME': 'Basic', 'KESTRA_API_TOKEN': credential, 'KESTRA_URL': 'http://kestra:8080', 'KESTRA_ROUTES_FILE': '/app/config/workflow-routes.json'})
    # Repository/queue are PostgreSQL: recreation preserves flow/execution state.
    run(compose('up', '-d', '--no-deps', '--force-recreate', 'kestra'))
    deadline = time.monotonic() + 90
    while True:
        try:
            api(live, '/api/v1/flows/search')
            break
        except (OSError, Refused):
            if time.monotonic() >= deadline:
                raise Refused('Kestra readiness timed out') from None
            time.sleep(1)
    unique = {(f['namespace'], f['id']): f for _, f in entries}
    for (namespace, flow_id), flow in unique.items():
        # Upsert via POST for initial import, PUT for already-persisted declarations.
        try:
            api(live, '/api/v1/flows/' + namespace + '/' + flow_id)
            method, path = 'PUT', '/api/v1/flows/' + namespace + '/' + flow_id
        except Refused:
            method, path = 'POST', '/api/v1/flows'
        api(live, path, yaml.safe_dump(flow).encode(), method, 'application/x-yaml')
    run(compose('up', '-d', '--no-deps', '--build', 'cap-process'))
    private_json(ROOT / 'build/integration/workflow-deployment.json', {'routes': routes, 'renewed_at': int(time.time()), 'token_expires_at': claims['exp']})
    print(json.dumps({'result': 'deployed', 'workflows': len(unique), 'workspace_routes': len(routes), 'persistent_queue': 'postgres'}))


def verify_ready(live):
    """Check both declared app routes, deployed flows, auth and actual process config."""
    entries = [(r, f) for r, f in declarations(live) if r['workspace_id'] == live.workspace]
    routes = json.loads((ROOT / 'build/integration/workflow-routes.json').read_text())
    if live.config.get('KESTRA_AUTH_SCHEME') != 'Basic' or live.config.get('KESTRA_ROUTES_FILE') != '/app/config/workflow-routes.json':
        raise Refused('automatic phase requires deployed manifest routing and explicit auth')
    containers = json.loads(run(['docker', 'inspect', run(compose('ps', '-q', 'cap-process')).strip(), run(compose('ps', '-q', 'kestra')).strip()]))
    runtime = dict(v.split('=', 1) for v in containers[0]['Config']['Env'])
    secrets_env = dict(v.split('=', 1) for v in containers[1]['Config']['Env'])
    for key in ('KESTRA_AUTH_SCHEME', 'KESTRA_API_TOKEN', 'KESTRA_URL', 'KESTRA_ROUTES_FILE'):
        if runtime.get(key) != live.config.get(key):
            raise Refused('running publisher configuration differs from private deployment')
    for row, flow in entries:
        matching = [r for r in routes if r['workspace_id'] == row['workspace_id'] and r['app_id'] == row['app_id'] and r['version'] == row['version'] and r['workflow_id'] == flow['id']]
        key = base64.b64decode(secrets_env['SECRET_DXOS_WEBHOOK_KEY']).decode()
        expected = 'http://kestra:8080/api/v1/executions/webhook/' + flow['namespace'] + '/' + flow['id'] + '/' + key
        if len(matching) != 1 or matching[0]['endpoint'] != expected:
            raise Refused('actual workflow webhook routing differs from Ready declaration')
        actual = api(live, '/api/v1/flows/' + flow['namespace'] + '/' + flow['id'])
        if actual.get('disabled') or actual.get('tasks') != flow['tasks'] or actual.get('triggers') != flow['triggers']:
            raise Refused('actual deployed workflow differs from declared package')
    if len(entries) != 2:
        raise Refused('automatic fixture requires both actual app workflows')
    token = base64.b64decode(secrets_env['SECRET_DXOS_WORKFLOW_TOKEN']).decode()
    claims = json.loads(base64.urlsafe_b64decode(token.split('.')[1] + '=='))
    hasura = claims.get('https://hasura.io/jwt/claims', {})
    if claims['sub'] != live.fixture['actors']['workflow']['sub'] or hasura.get('x-hasura-workspace-id') != live.workspace or 'role_workflow' not in hasura.get('x-hasura-allowed-roles', []) or claims['exp'] < time.time() + 90:
        raise Refused('renew workflow service token before automatic phase')


def executions_for(live, case):
    flows = declarations(live)
    flow = next(f for r, f in flows if r['workspace_id'] == live.workspace and r['app_id'] == case['app_id'])
    result = api(live, '/api/v1/executions/search?namespace=' + flow['namespace'] + '&flowId=' + flow['id'] + '&size=100')
    return [e for e in result.get('results', []) if e.get('trigger', {}).get('variables', {}).get('body', {}).get('event_id') == case['event_id']]


def deliver(live, case):
    routes = json.loads((ROOT / 'build/integration/workflow-routes.json').read_text())
    route = next(r for r in routes if r['app_id'] == case['app_id'] and r['workspace_id'] == live.workspace)
    url = urlsplit(route['endpoint'])
    body = live.sql("SELECT payload FROM core.outbox_events WHERE id='%s'" % case['event_id']).encode()
    return api(live, url.path, body, 'POST')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['deploy', 'renew'])
    args = parser.parse_args()
    try:
        deploy(LiveSeed(), reload=args.action == 'renew')
    except (Refused, OSError, ValueError):
        parser.exit(1, 'workflow deployment failed; inspect private diagnostics and service readiness\n')
