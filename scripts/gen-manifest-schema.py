"""Derive contracts/manifest-v1.schema.json from the DXApplication CRD.

The manifest file and the custom resource share their spec. The file keeps
displayName and version in metadata and names each workflow's file instead of
inlining its definition.

    scripts/gen-manifest-schema.py          rewrite the schema
    scripts/gen-manifest-schema.py --check  fail when the schema is stale
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
CRD = ROOT / "operator/config/crd/bases/dxos.io_dxapplications.yaml"
SCHEMA = ROOT / "contracts/manifest-v1.schema.json"
IDENTIFIER = "^[a-z][a-z0-9_]*$"


def close(node):
    """Forbid undeclared fields and turn free-form CRD fields into objects."""
    if isinstance(node, list):
        return [close(item) for item in node]
    if not isinstance(node, dict):
        return node
    out = {key: close(value) for key, value in node.items()}
    if out.pop("x-kubernetes-preserve-unknown-fields", False):
        out["type"] = "object"
    if "properties" in out:
        out["additionalProperties"] = False
    return out


def build():
    crd = yaml.safe_load(CRD.read_text(encoding="utf-8"))
    spec = close(crd["spec"]["versions"][0]["schema"]["openAPIV3Schema"]["properties"]["spec"])
    for moved in ("displayName", "version"):
        del spec["properties"][moved]
        spec["required"].remove(moved)
    workflow = spec["properties"]["workflows"]["items"]
    del workflow["properties"]["definition"]
    workflow["required"] = [name for name in workflow["required"] if name != "definition"] + ["file"]
    text = {"type": "string", "minLength": 1}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://dxos.io/contracts/manifest-v1.schema.json",
        "title": "DXApplication manifest (dxos.io/v1alpha1)",
        "$comment": "Generated by scripts/gen-manifest-schema.py from the DXApplication CRD "
        "(operator/config/crd/bases). Semantic rules (declared roles, scopes, capabilities, "
        "column references) are enforced by operator/internal/manifest.Validate.",
        "type": "object",
        "additionalProperties": False,
        "required": ["apiVersion", "kind", "metadata", "spec"],
        "properties": {
            "apiVersion": {"const": "dxos.io/v1alpha1"},
            "kind": {"const": "DXApplication"},
            "metadata": {
                "type": "object",
                "additionalProperties": False,
                "required": ["name", "displayName", "version"],
                "properties": {
                    "name": {"type": "string", "pattern": IDENTIFIER},
                    "displayName": text,
                    "version": text,
                },
            },
            "spec": spec,
        },
    }


def main():
    rendered = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv[1:]:
        if SCHEMA.read_text(encoding="utf-8") != rendered:
            sys.exit(f"{SCHEMA.relative_to(ROOT)} is stale; run scripts/gen-manifest-schema.py")
        return
    SCHEMA.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
